PROMPT_REGISTRY = {
    PROJECT_OVERVIEW_PROMPT_ID: {
        "name": "Project Overview",
        "description": (
            "Prompt used to synthesize a structured project overview from STAR project "
            "metadata, reported results and uploaded evidence."
        ),
        "defaults": DEFAULT_PROMPT_DOCUMENT_OVERVIEW,
        "variables": PROJECT_OVERVIEW_VARIABLES,
    },
}


def is_known_prompt_id(prompt_id: str) -> bool:
    return prompt_id in PROMPT_REGISTRY


def known_prompt_ids() -> list[str]:
    return sorted(PROMPT_REGISTRY)


def get_prompt_definition(prompt_id: str) -> dict:
    """Return the registry entry for a prompt ID.

    Raises:
        ValueError: If the prompt ID is not registered.
    """
    definition = PROMPT_REGISTRY.get(prompt_id)
    if definition is None:
        raise ValueError(
            f"Unknown prompt id '{prompt_id}'. Known ids: {', '.join(known_prompt_ids())}"
        )
    return definition


def get_default_sections(prompt_id: str) -> dict[str, str]:
    """Copy of the code-defined default sections for a prompt ID."""
    return dict(get_prompt_definition(prompt_id)["defaults"])


def get_variables(prompt_id: str) -> tuple[PromptVariable, ...]:
    return get_prompt_definition(prompt_id)["variables"]
