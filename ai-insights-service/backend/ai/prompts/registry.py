"""Registry of the prompts managed through the STAR Prompt Manager.

Each entry is keyed by a prompt ID (the service or module name) and holds the
default section text plus the template variables that section text may reference.

Adding a new prompt here is all it takes to expose it through /api/prompts: the
GET seeds missing S3 records from these defaults, so there is no manual step.
"""

from ai.prompts.prompt_document_overview import DEFAULT_PROMPT_DOCUMENT_OVERVIEW

PROJECT_OVERVIEW_PROMPT_ID = "project-overview"

# Section keys, in the order they are assembled into the final prompt.
PROMPT_SECTIONS = (
    "system_role",
    "context",
    "user_instructions",
    "expected_output_format",
)


class PromptVariable:
    """A `{placeholder}` the service replaces with real context at generation time."""

    def __init__(self, name: str, description: str, required: bool = True):
        self.name = name
        self.description = description
        self.required = required

    @property
    def placeholder(self) -> str:
        return "{" + self.name + "}"

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "placeholder": self.placeholder,
            "description": self.description,
            "required": self.required,
        }


